export const DEFAULT_TEXT: Record<string, string> = Object.fromEntries(TEXT_GROUPS.flatMap((g) => g.fields.map((x) => [x.key, x.def])));

export type SiteText = Record<string, string>;
export type T = (key: string, vars?: Record<string, string | number>) => string;

/** Text lookup: the owner's version, else the default. Fills {placeholders}. */
export function makeT(over?: SiteText): T {
  return (key, vars) => {
    const raw = over?.[key]?.trim() ? over[key] : DEFAULT_TEXT[key] ?? key;
    return vars ? raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : raw;
  };
}

/** The text without *accent* markers, for labels and attributes. */
export const plain = (s: string) => s.replace(/\*([^*]+)\*/g, "$1");
